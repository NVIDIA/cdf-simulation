"""SCRATCH / EXPERIMENTAL -- wet-triangles investigation.

Stage 4, the payoff test: take the labelled, closed boolean body and emit it as a
Surface Evolver datafile with a NATIVE ``body ... volume`` constraint -- no
``content: c1/c2/c3`` divergence trick -- then let the real evolver binary report
the volume back.  If Evolver's own volume matches the mesh volume we computed,
the body is genuinely closed and consistently oriented as far as Evolver is
concerned, which is the whole point of the wet triangles.

Wetted facets get tension ``-cos(theta)`` for their surface; the meniscus gets 1.
The contact line is PINNED: every vertex on a meniscus/wet boundary is ``fixed``,
and so is every wet-patch vertex (the wet patches do not move).

    .venv/bin/python -m pcb_aoi.solder_evolver.emit \
        --family D2PAK --joint 1 --blob aperture_offset --run
"""

from __future__ import annotations

import argparse
import os
import subprocess
import tempfile

import numpy as np

from . import boolean as wb


def emit(V, F, lab, theta, keepout=None, gtol=1e-8, gmax=4000, gblk=20,
         hmax=40, hmaxscale=0.0):
    """Closed triangle body -> .fe text. `theta` maps label -> contact angle deg
    (None for the meniscus, which keeps tension 1).

    `keepout` optionally adds the grid-SDF collider: a dict with `grid` (the
    .bin filename, resolved relative to the datafile's directory) and `kpen`
    (stiffness). The keep-out is a penalty ENERGY, not a one-sided constraint --
    Evolver acquires one-sided constraints only at load time, so a vertex that
    wanders into the solid during `g` would never be caught (see
    third_party/evolver/tests/test_sdf_collider.py). `facet_scalar_integral`
    samples via Gaussian cubature, so it also sees a facet spanning a thin lead.

    This matters at low fill: with only the contact line pinned, a starved joint
    has nothing stopping the meniscus being sucked through the termination.

    `gtol`/`gmax`/`gblk` size the `converge` command (gradient descent);
    `hmax`/`hmaxscale` size `hconverge` (Newton via `hessian_seek`). Both are
    defined unconditionally -- they cost two datafile commands and nothing at
    all if unused -- so the caller picks the minimiser at solve time rather than
    at emit time. `hmaxscale=0` leaves hessian_seek's own default (10).
    """
    L = ["// generated by pcb_aoi.solder_evolver.emit -- native closed body"]
    if keepout:
        # `-(usr3)` and not `-usr3`: the lexer mis-tokenises usrN before an
        # operator. usr3 is the sdf1 collider slot (third_party/evolver/src).
        #
        # NOT `global`: the quantity is attached to the meniscus facets only
        # (verified that per-facet attachment works -- 2 of 6 facets integrate to
        # exactly 2/6 of the field). The wet patches are `fixed`, so a keep-out
        # on them can never move anything; it would only add a constant. That
        # matters once the grid is INFLATED, because the wet patches then sit a
        # full inflation depth inside the keep-out and their constant would
        # swamp the reported energy (~0.2 against a total of ~0.85).
        L += [f"parameter kpen = {float(keepout['kpen']):.6g}",
              "quantity keepout energy method facet_scalar_integral",
              "scalar_integrand: kpen*(maximum(-(usr3),0))^2", ""]
    L.append("vertices")
    wet_v = set()
    for i, t in enumerate(F):
        if lab[i] != "meniscus":
            wet_v.update(int(x) for x in t)
    for k, p in enumerate(V, 1):
        fx = " fixed" if (k - 1) in wet_v else ""
        L.append(f"{k} {p[0]:.9g} {p[1]:.9g} {p[2]:.9g}{fx}")

    edir, elist = {}, []

    def E(u, v):
        if (u, v) in edir:
            return edir[(u, v)]
        if (v, u) in edir:
            return -edir[(v, u)]
        eid = len(elist) + 1
        elist.append((u, v)); edir[(u, v)] = eid
        return eid

    facets = []
    for i, t in enumerate(F):
        a, b, c = (int(x) + 1 for x in t)
        facets.append(([E(a, b), E(b, c), E(c, a)], lab[i]))

    L.append("edges")
    for k, (u, v) in enumerate(elist, 1):
        fx = " fixed" if ((u - 1) in wet_v and (v - 1) in wet_v) else ""
        L.append(f"{k} {u} {v}{fx}")

    L.append("faces")
    for k, (loop, lb) in enumerate(facets, 1):
        if lb == "meniscus":
            # only the free surface can move, so only it carries the keep-out
            tag = " keepout" if keepout else ""
        else:
            th = theta.get(lb, 40.0)
            tag = f" tension {-np.cos(np.radians(th)):.6f} fixed"
        L.append(f"{k} {' '.join(map(str, loop))}{tag}")

    vol = wb.signed_volume(V, F)
    L.append("bodies")
    L.append(f"1 {' '.join(str(i) for i in range(1, len(facets) + 1))} volume {vol:.9g}")
    L.append("read")
    if keepout:
        # Naming the grid from the datafile (rather than an env var or a command
        # line flag) keeps the obstacle with the geometry that needs it. The
        # collider loads LAZILY on first evaluation, which is what makes this
        # work: constraints are evaluated at read time, before `read` runs.
        L += ["define sdf1_file string",
              f'sdf1_file := "{keepout["grid"]}"']

    # A convergence loop, run AFTER the fixed opening recipe. The recipe ends on
    # a fixed iteration count, which is not a stopping criterion -- measured on a
    # starved 0805 the energy was still falling at -6e-4 per 100 steps when it
    # stopped, and vertices were still moving 2e-3 mm.
    #
    # Evolver is an interactive interpreter with its own scripting language, so
    # the stopping rule belongs here rather than in Python: no round-trip per
    # block, and it runs at Evolver speed.
    #
    # `g` will not take a variable iteration count (`g gblk` is a syntax error),
    # so the block size is baked in. Plain gradient descent only -- no conjugate
    # gradient, no Hessian.
    L += [
        "",
        f"gtol := {float(gtol):g}          // relative energy tolerance",
        f"gmax := {int(gmax)}              // hard cap on iterations",
        "gsteps := 0",
        "golde := 0",
        "converge := {",
        "  golde := total_energy + 1 + abs(total_energy);",
        "  gsteps := 0;",
        "  while ((golde - total_energy) > gtol*(1+abs(total_energy)))",
        "        and (gsteps < gmax) do {",
        "    golde := total_energy;",
        f"    g {int(gblk)};",
        f"    gsteps := gsteps + {int(gblk)};",
        "  };",
        "}",
    ]

    # The NEWTON counterpart, same stopping rule, one `hessian_seek` per step.
    #
    # `hessian_seek` and not `hessian`: raw `hessian` takes the Newton step at
    # stepsize exactly 1 and only WARNS when the factored matrix is indefinite
    # (bk.c: "Hessian not positive definite. Index: %d") -- it moves anyway.
    # That is how the previous attempt at this blew up (commit e6db6ec:
    # "overshoot on these free surfaces -- they invert triangles"). The matrix
    # here is *knowingly* indefinite: the fixed body volume enters as a bordered
    # KKT row whose Lagrange multiplier is the pressure, so the assembled system
    # is a saddle-point system and has negative eigenvalues BY CONSTRUCTION.
    # `hessian_seek` line-searches along the same Newton direction and only
    # commits to a step that actually lowers the energy, which turns "indefinite"
    # from fatal into merely slow.
    #
    # It is also the right tool for our keep-out penalty being C1 but not C2.
    # `kpen*(maximum(-(usr3),0))^2` differentiates in Evolver by simply taking
    # the winning branch's derivatives (eval_sec.c MAXIMUM_NODE copies the whole
    # dstack), so the Hessian jumps from 2*kpen*|grad f|^2 to 0 across the
    # contact boundary. A Newton method on a discontinuous Hessian can propose a
    # step computed for the wrong branch; a line search simply rejects it. We do
    # NOT smooth the penalty to make it C2, because doing so changes the PHYSICS
    # (the equilibrium penetration depth) to fix what is really a step-acceptance
    # problem -- and the measured line search rejects such steps for free.
    #
    # `last_hessian_scale` is how the loop learns the search failed: hessian_seek
    # returns 0 when no step in either direction helps, which is the real
    # convergence signal here and fires long before the energy test would.
    L += [
        "",
        f"hmax := {int(hmax)}              // cap on Newton steps per block",
        "hsteps := 0",
        "holde := 0",
        "hscale := 1",
        "hconverge := {",
        "  holde := total_energy + 1 + abs(total_energy);",
        "  hsteps := 0;",
        "  hscale := 1;",
        "  while ((holde - total_energy) > gtol*(1+abs(total_energy)))",
        "        and (hsteps < hmax) and (hscale > 0) do {",
        "    holde := total_energy;",
        # A bounded maxscale is available because the default is 10, and a
        # 10x Newton step on a surface this floppy is a long way outside the
        # region where the quadratic model means anything. 0 = use the default.
        ("    hessian_seek;" if not hmaxscale
         else f"    hessian_seek {float(hmaxscale):g};"),
        "    hscale := last_hessian_scale;",
        "    hsteps := hsteps + 1;",
        "  };",
        "}",
    ]
    return "\n".join(L) + "\n", vol


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--family", default="D2PAK")
    ap.add_argument("--joint", type=int, default=1)
    ap.add_argument("--blob", default="aperture_offset")
    ap.add_argument("--dil", type=float, default=0.25)
    ap.add_argument("--stencil", type=float, default=0.13)
    ap.add_argument("--seat", type=float, default=0.003)
    ap.add_argument("--theta-board", type=float, default=35.0)
    ap.add_argument("--theta-comp", type=float, default=25.0)
    ap.add_argument("--run", action="store_true", help="invoke /usr/bin/evolver")
    ap.add_argument("--out", default="")
    a = ap.parse_args()

    d = np.load(os.path.join(wb.OUT, f"{a.family}.npz"))
    pad_z = float(d["pad_z"])
    # Drive the SHARED pipeline. This used to be a copy of cut_joint's body, and
    # it silently drifted the moment cut_joint learned to lift the component off
    # the board: the viewer showed a seated part while the .fe still had it buried.
    # Two implementations of "the geometry" is exactly the bug cut_joint exists
    # to prevent, so call it.
    res = wb.cut_joint(d, a.joint, a.blob, stencil=a.stencil, dil=a.dil,
                       seat=a.seat, verbose=False)
    V, F, lab = res["V"], res["F"], np.asarray(res["lab"]).astype(str)
    vol = res["target_volume"]
    if res["lift"]:
        print(f"  component lifted +{res['lift']:.4f} mm off the board "
              f"(gap at this joint {res['clearance']:+.4f} mm)")
    theta = {"wet_board": a.theta_board, "wet_metal": a.theta_comp,
             "wet_body": a.theta_comp}
    text, mvol = emit(V, F, lab, theta)

    path = a.out or os.path.join(tempfile.mkdtemp(prefix="wet_fe_"), "wet.fe")
    open(path, "w").write(text)
    print(f"wrote {path}  V={len(V)} F={len(F)}  mesh volume={mvol:.9g} "
          f"(paste target {vol:.9g})")
    uniq, cnt = np.unique(lab, return_counts=True)
    print("  facets: " + ", ".join(f"{u}={c}" for u, c in zip(uniq, cnt)))

    if a.run:
        script = ("printf \"EVOLVER_VOLUME %.12g\\n\", body[1].volume;\n"
                  "printf \"EVOLVER_AREA %.12g\\n\", total_area;\n"
                  "printf \"EVOLVER_ENERGY %.12g\\n\", total_energy;\n"
                  "g 5;\n"
                  "printf \"AFTER_G5_VOLUME %.12g\\n\", body[1].volume;\n"
                  "printf \"AFTER_G5_ENERGY %.12g\\n\", total_energy;\n"
                  "q\nq\n")
        sp = path + ".cmd"
        open(sp, "w").write(script)
        from .backend import die_with_parent_kwargs

        r = subprocess.run(["/usr/bin/evolver", "-x", "-f", sp, path],
                           capture_output=True, text=True, timeout=300,
                           **die_with_parent_kwargs())
        for line in (r.stdout + r.stderr).splitlines():
            if ("EVOLVER_" in line or "AFTER_" in line or "rror" in line
                    or "arning" in line or "not closed" in line.lower()):
                print("  evolver| " + line.strip())
        print(f"  evolver exit={r.returncode}")


if __name__ == "__main__":
    main()
